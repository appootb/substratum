package generator

import (
	"path"
	"sort"
	"strings"
	"text/template"

	pgs "github.com/lyft/protoc-gen-star/v2"
	pgsgo "github.com/lyft/protoc-gen-star/v2/lang/go"
)

const (
	DartExportGenerator = "dart-export"
	FileParam           = "file"
	PrefixParam         = "prefix"

	defaultOutFile = "export.dart"
	defaultPrefix  = "./src/generated"
)

type DartExport struct {
	*pgs.ModuleBase
	ctx pgsgo.Context
}

type exportData struct {
	Prefix string
	Files  []pgs.File
}

func New() pgs.Module {
	return &DartExport{
		ModuleBase: &pgs.ModuleBase{},
	}
}

func (m *DartExport) InitContext(ctx pgs.BuildContext) {
	m.ModuleBase.InitContext(ctx)
	m.ctx = pgsgo.InitContext(ctx.Parameters())
}

func (m *DartExport) Name() string {
	return DartExportGenerator
}

func (m *DartExport) Execute(targets map[string]pgs.File, _ map[string]pgs.Package) []pgs.Artifact {
	if len(targets) == 0 {
		return nil
	}

	files := sortedFiles(targets)
	outDir, ok := outputDir(files, m.ctx)
	if !ok {
		m.Fail("dart-export: unable to resolve output directory from target files")
		return nil
	}

	data := exportData{
		Prefix: normalizePrefix(m.Parameters().Str(PrefixParam)),
		Files:  files,
	}
	outFile := normalizeOutFile(m.Parameters().Str(FileParam))
	dartOut := pgs.JoinPaths(outDir.String(), outFile)

	m.Push("export")
	m.AddGeneratorTemplateFile(dartOut.String(), exportTemplate, data)
	m.Pop()

	return m.Artifacts()
}

func sortedFiles(targets map[string]pgs.File) []pgs.File {
	files := make([]pgs.File, 0, len(targets))
	for _, f := range targets {
		files = append(files, f)
	}
	sort.Slice(files, func(i, j int) bool {
		return files[i].InputPath().String() < files[j].InputPath().String()
	})
	return files
}

func outputDir(files []pgs.File, ctx pgsgo.Context) (pgs.FilePath, bool) {
	for _, f := range files {
		out := ctx.OutputPath(f)
		if out != "" {
			return out.Dir(), true
		}
	}
	return "", false
}

func normalizeOutFile(name string) string {
	if name == "" {
		return defaultOutFile
	}
	if path.Ext(name) == "" {
		return name + ".dart"
	}
	return name
}

func normalizePrefix(prefix string) string {
	if prefix == "" {
		return defaultPrefix
	}
	return strings.TrimRight(prefix, "/")
}

var exportTemplate = template.Must(template.New("export").Parse(exportTpl))

const exportTpl = `// Code generated by protoc-gen-dart-export. DO NOT EDIT!
{{ range .Files -}}
{{- $name := .InputPath.BaseName -}}
{{- if .Messages }}
export '{{ $.Prefix }}/{{ $name }}.pb.dart';
{{- end -}}
{{- if .Enums }}
export '{{ $.Prefix }}/{{ $name }}.pbenum.dart';
{{- end -}}
{{- if .Services }}
export '{{ $.Prefix }}/{{ $name }}.pbgrpc.dart';
{{- end -}}
{{- if .Messages }}
export '{{ $.Prefix }}/{{ $name }}.pbjson.dart';
{{- end }}
{{ end -}}
`
